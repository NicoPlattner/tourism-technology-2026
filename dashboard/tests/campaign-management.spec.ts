test('transfer, edit, approve, schedule, reschedule and refresh keep the exact campaign', async ({page}) => {
  let calls = 0;
  await page.route('**/api/marketing/generate-caption', route => { calls++; return route.abort(); });
  await page.goto('./');
  const caption = await page.locator('.cp-caption-text').innerText();
  const image = await page.locator('.cp-social-image').getAttribute('src');
  await page.getByRole('button',{name:'Review & Schedule'}).click();
  const card = page.locator('.am-campaign.is-open');
  await expect(card.locator('.am-creative img')).toHaveAttribute('src',image!);
  await expect(card.locator('.am-creative .am-caption')).toHaveText(caption);
  await expect(card.getByRole('button',{name:'Schedule posts',exact:true})).toBeDisabled();
  await expect(page.getByRole('button',{name:'2026-12-17, 0 scheduled posts',exact:true})).toBeVisible();
  const post = card.locator('.am-post').first();
  await post.getByRole('button',{name:'Edit post'}).click();
  await post.getByLabel('Post caption').fill('Unser nächstes Alpenabenteuer wartet. Komm mit!');
  await post.getByLabel('Publishing date & time').fill('2026-12-18T19:30');
  await post.getByRole('button',{name:'Save post'}).click();
  await card.getByRole('button',{name:'Approve campaign',exact:true}).click();
  await expect(page.getByRole('button',{name:'2026-12-18, 0 scheduled posts',exact:true})).toBeVisible();
  await card.getByRole('button',{name:'Schedule posts',exact:true}).click();
  await expect(card.locator('.am-status')).toHaveText('SCHEDULED');
  await expect(page.getByRole('button',{name:'2026-12-18, 1 scheduled posts',exact:true})).toHaveAttribute('aria-pressed','true');
  await expect(page.locator('.am-calendar-post')).toContainText('TikTok · 19:30');
  await post.getByRole('button',{name:'Edit post'}).click();
  await post.getByLabel('Publishing date & time').fill('2026-12-19T20:00');
  await post.getByRole('button',{name:'Save post'}).click();
  await expect(page.getByRole('button',{name:'2026-12-18, 0 scheduled posts',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'2026-12-19, 1 scheduled posts',exact:true}).click();
  await expect(page.locator('.am-calendar-post')).toContainText('20:00');
  await page.reload();
  await expect(page.locator('.am-campaign.is-open .am-status')).toHaveText('SCHEDULED');
  await expect(page.locator('.am-campaign.is-open .am-post').first()).toContainText('Unser nächstes Alpenabenteuer');
  await expect(page.locator('.am-campaign')).toHaveCount(4);
  await expect(page.locator('.am-stats')).toContainText('9Scheduled posts');
  expect(calls).toBe(0);
});
